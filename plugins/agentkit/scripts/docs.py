#!/usr/bin/env python3
"""agentkit docs tooling, one source for CI, the Stop hook and local use.

  docs.py check            front matter schema, `covers` globs match files, relative links resolve,
                           decided RFCs have a decision record, `supersedes` targets are superseded
  docs.py index [--check]  write docs/README.md (or fail if it is stale)
  docs.py drift BASE [--pr-body FILE]
                           docs whose `covers` code changed since BASE but the doc did not
  docs.py hook             Stop hook: all of the above, exit 2 with a message for Claude

Every command is a no-op (exit 0) in a repo without docs/.
Front matter is a small YAML subset: `key: value`, `key: [a, b]`, or `key:` followed by `  - item` lines.
"""
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

DOCS = Path("docs")
INDEX = DOCS / "README.md"
STATUSES = {"draft", "current", "deprecated", "proposed", "accepted", "rejected", "superseded"}
INDEX_HEADER = "# Docs\n\n<!-- generated by `docs.py index` (agentkit); do not edit by hand -->\n"
TICK = re.compile(r"^\s*- \[[xX]\] docs reviewed: (\S+)", re.M)
LINK = re.compile(r"\]\(([^)\s]+)\)")


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout.splitlines()


def front_matter(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    meta, key = {}, None
    for line in lines[1:]:
        if line.strip() == "---":
            return meta
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and key:
            meta[key].append(clean(item.group(1)))
            continue
        kv = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not kv:
            continue
        key, value = kv.group(1), clean(kv.group(2))
        if value.startswith("[") and value.endswith("]"):
            meta[key] = [clean(v) for v in value[1:-1].split(",") if clean(v)]
        else:
            meta[key] = value if value else []
    return None  # no closing ---


def clean(value):
    value = re.sub(r"\s+#.*$", "", value).strip()
    return value[1:-1] if len(value) > 1 and value[0] == value[-1] and value[0] in "\"'" else value


def docs():
    return sorted(p for p in DOCS.rglob("*.md") if p != INDEX)


def as_list(value):
    return value if isinstance(value, list) else ([value] if value else [])


def matches(path, patterns):
    return any(fnmatch.fnmatchcase(path, p) for p in patterns)


def check():
    errors, files = [], git("ls-files")
    for doc in docs():
        meta = front_matter(doc)
        if meta is None:
            errors.append(f"{doc}: missing front matter (--- title/status ---)")
            continue
        if not meta.get("title"):
            errors.append(f"{doc}: `title` is required")
        if meta.get("status") not in STATUSES:
            errors.append(f"{doc}: `status` must be one of {', '.join(sorted(STATUSES))}")
        for pattern in as_list(meta.get("covers")):
            if not any(fnmatch.fnmatchcase(f, pattern) for f in files):
                errors.append(f"{doc}: covers `{pattern}` matches no tracked file (moved or deleted code?)")
        for target in LINK.findall(doc.read_text(encoding="utf-8")):
            target = target.split("#")[0]
            if target and not re.match(r"^[a-z][a-z0-9+.-]*:", target) and not (doc.parent / target).exists():
                errors.append(f"{doc}: broken link `{target}`")
    return errors + decision_errors()


def decision_errors():
    """An accepted or rejected RFC needs a decision record linking to it; `supersedes` targets must be superseded."""
    errors, decisions = [], [d for d in docs() if d.parts[1:2] == ("decisions",)]
    linked = {os.path.normpath(d.parent / t.split("#")[0]) for d in decisions for t in LINK.findall(d.read_text(encoding="utf-8"))}
    for doc in (d for d in docs() if d.parts[1:2] == ("rfcs",)):
        status = (front_matter(doc) or {}).get("status")
        if status in ("accepted", "rejected") and os.path.normpath(doc) not in linked:
            errors.append(f"{doc}: `{status}` RFC has no decision record in docs/decisions/ linking to it")
    by_number = {d.name.split("-")[0]: d for d in decisions}
    for d in decisions:
        for number in as_list((front_matter(d) or {}).get("supersedes")):
            target = by_number.get(number)
            if target is None:
                errors.append(f"{d}: supersedes {number}, which does not exist")
            elif (front_matter(target) or {}).get("status") != "superseded":
                errors.append(f"{d}: supersedes {number}, which is not `status: superseded`")
    return errors


def render_index():
    rows, section = [INDEX_HEADER], None
    for doc in docs():
        meta = front_matter(doc) or {}
        rel = doc.relative_to(DOCS)
        group = rel.parts[0] if len(rel.parts) > 1 else "general"
        if group != section:
            section = group
            rows.append(f"\n## {group}\n\n| Doc | Status | About |\n|---|---|---|\n")
        title = meta.get("title") or doc.stem
        about = meta.get("description") or ""
        rows.append(f"| [{title}]({rel.as_posix()}) | {meta.get('status', '')} | {about} |\n")
    return "".join(rows)


def changed_since(base):
    files = set(git("diff", "--name-only", f"{base}...HEAD"))
    files |= set(git("diff", "--name-only", "HEAD"))
    files |= set(git("ls-files", "--others", "--exclude-standard"))
    return files


def drift(base, pr_body=""):
    changed, reviewed = changed_since(base), set(TICK.findall(pr_body))
    stale = []
    for doc in docs():
        path = doc.as_posix()
        covers = as_list((front_matter(doc) or {}).get("covers"))
        hits = sorted(f for f in changed if matches(f, covers))
        if hits and path not in changed and path not in reviewed:
            stale.append(f"- [ ] docs reviewed: {path} (its code changed: {', '.join(hits[:5])})")
    return stale


def default_base():
    if os.environ.get("AGENTKIT_BASE"):
        return os.environ["AGENTKIT_BASE"]
    for ref in ("origin/HEAD", "origin/main", "origin/master"):
        if subprocess.run(["git", "rev-parse", "-q", "--verify", ref], capture_output=True).returncode == 0:
            return ref
    return "HEAD"


def main(argv):
    root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()
    if root:
        os.chdir(root)
    if not DOCS.is_dir():
        return 0
    cmd = argv[0] if argv else ""
    if cmd == "check":
        errors = check()
        print("\n".join(errors) or "docs: ok")
        return 1 if errors else 0
    if cmd == "index":
        text = render_index()
        if "--check" in argv:
            stale = not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text
            if stale:
                print("docs/README.md is stale: run `python3 <agentkit>/scripts/docs.py index`")
            return 1 if stale else 0
        INDEX.write_text(text, encoding="utf-8")
        return 0
    if cmd == "drift":
        body = Path(argv[3]).read_text(encoding="utf-8") if len(argv) > 3 and argv[2] == "--pr-body" else ""
        stale = drift(argv[1], body)
        if stale:
            print("Code these docs describe changed, but the docs did not. Update each doc, or, if it is"
                  " still accurate, add the line ticked to the PR description with a short reason:")
            print("\n".join(stale))
        return 1 if stale else 0
    if cmd == "hook":
        if json.loads(sys.stdin.read() or "{}").get("stop_hook_active"):
            return 0
        problems = check() + drift(default_base())
        if render_index() != (INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""):
            problems.append("docs/README.md is stale: regenerate it with `docs.py index`")
        if problems:
            print("agentkit docs check. Before stopping, update the docs (or, for a doc that is still accurate,"
                  " put a ticked `- [x] docs reviewed: <path> — <why>` line in your final summary):\n"
                  + "\n".join(problems), file=sys.stderr)
            return 2
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
